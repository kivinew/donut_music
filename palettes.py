# Функция для получения интерполированной палитры между двумя существующими
def interpolate_palette(palette1, palette2, t):
    """Создаёт плавный переход между двумя палитрами, t от 0 до 1"""
    result = []
    for i in range(len(palette1)):
        c1 = palette1[i]
        c2 = palette2[i]
        
        bg1 = (c1 >> 4) & 0x0F
        fg1 = c1 & 0x0F
        bg2 = (c2 >> 4) & 0x0F
        fg2 = c2 & 0x0F
        
        bg = int(bg1 + (bg2 - bg1) * t)
        fg = int(fg1 + (fg2 - fg1) * t)
        
        result.append((bg << 4) | fg)
    return result

